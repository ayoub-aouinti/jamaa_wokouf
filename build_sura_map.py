LOOKUP = {}
for num, forms in NAMES.items():
    for f in forms:
        LOOKUP.setdefault(nrm(f), num)

# الاسمُ الواحد قد يكون لسورتين: الدانيُّ يسمّي فصلت «السجدة» كما يسمّي
# الثانيةَ والثلاثين، فلا يُفصَل بينهما بالاسم وحده. وجميعُ هذه الكتب تمشي
# على ترتيب المصحف، فيُرجَّح بالترتيب: يُؤخذ أصغرُ المحتملَين بعد ما سبق.
MULTI = {}
for num, forms in NAMES.items():
    for f in forms:
        MULTI.setdefault(nrm(f), set()).add(num)
MULTI['السجده'] = {32, 41}

# ما يسبق الاسم في عناوين المطبوعات القديمة
STRIP = re.compile(r'^(سوره|السوره التي يذكر فيها|السوره التي تذكر فيها|'
                   r'وقوفهم في سوره|وقوفهم في|باب|فاتحه)\s*')
BRACKET = re.compile(r'[\[\]()«»"]')


def resolve(name, after=0):
    """after: آخرُ سورةٍ رُصدت، يُرجَّح بها عند اشتباه الاسم بين سورتين."""
    t = nrm(BRACKET.sub(' ', name))
    # الاسمُ المعروفُ كما هو يُقدَّم على تجريده: نمطُ التجريد يحذف «فاتحه»
    # من أوائل الأسماء (لنحو «فاتحة سورة كذا»)، فكان يُحيل «فاتحة الكتاب»
    # إلى «الكتاب» وليست سورة، فتسقط الفاتحةُ من خريطة كلِّ كتابٍ سمّاها بها.
    if t in LOOKUP:
        return LOOKUP[t]
    t = STRIP.sub('', t).strip()
    # واوُ القسم في أسماء السور: «والشمس وضحاها» هي «الشمس»
    if t not in LOOKUP and t.startswith('و') and t[1:].strip() in LOOKUP:
        t = t[1:].strip()
    cands = MULTI.get(t)
    if cands and len(cands) > 1:
        nxt = sorted(c for c in cands if c > after)
        if nxt:
            return nxt[0]
    if t in LOOKUP:
        return LOOKUP[t]
    # «الفلق والناس» ونحوه: أولُ اسمٍ يُعرف
    for part in re.split(r'\s+و|^و', t):
        p = part.strip()
        if p in LOOKUP:
            return LOOKUP[p]
    for key, num in LOOKUP.items():
        if key and (t.endswith(' ' + key) or t.startswith(key + ' ')):
            return num
    return None


def main(pattern, out_json, book_name):
    seen, unknown = {}, []
    for path in sorted(glob.glob(pattern)):
        for ln in open(path, encoding='utf-8'):
            ln = ln.strip()
            if not ln.startswith('#سورة'):
                continue
            parts = [x.strip() for x in ln.split('|')]
            if len(parts) < 3:
                continue
            try:
                # الصفحةُ قد تحمل الجزء («ج1/ص170») في الكتب المجلَّدة،
                # فتُقرأ بنفس دالّة المحاذاة ليتّحد فضاءُ الترقيم بينهما
                pr = read_page(parts[1])
                if pr is None:
                    continue
                page = pr[0]
            except ValueError:
                continue
            num = resolve(parts[2], max(seen, default=0))
            if num is None:
                unknown.append(parts[2])
                continue
            # أولُ صفحةٍ ذُكرت فيها السورة هي مبدؤها
            if num not in seen or page < seen[num]:
                seen[num] = page
    starts = sorted(((p, n) for n, p in seen.items()))
    # لا يصحّ أن ترجع السورُ إلى الوراء؛ فما خالف الترتيب فهو إحالةٌ لا مبدأ
    clean, last = [], 0
    for p, n in starts:
        if n > last:
            clean.append([p, n])
            last = n
    json.dump({'book': book_name,
               'note': 'أوائل صفحات السور كما رُصدت من عناوين المتن أثناء الاستخراج.',
               'starts': clean},
              open(out_json, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('سور مرصودة:', len(clean), '· من', clean[0] if clean else '-',
          'إلى', clean[-1] if clean else '-')
    if unknown:
        print('عناوين لم تُعرف:', sorted(set(unknown))[:10])


if __name__ == '__main__':
    main(*sys.argv[1:4])
